#!/usr/bin/env node
// Generates src/lib/api/roles.gen.ts: the minimum role of every admin operation, read from the
// contract's `x-required-role` (HUB-288). The console hides each control unless the signed-in role
// satisfies the role of the operation it calls, so the contract stays the only source of truth.
// The output is typed (`satisfies Record<keyof operations, Role>`), so `npm run check` fails when an
// operation is added or removed without regenerating. Run via `npm run gen:api`; never edit the
// output by hand. `--check` exits 1 if the file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const SPEC = join(root, '..', 'contracts', 'openapi', 'hub-admin.v1.yaml');
const OUT = join(root, 'src', 'lib', 'api', 'roles.gen.ts');
const METHODS = ['get', 'put', 'post', 'patch', 'delete'];
const ROLES = ['tenant_viewer', 'tenant_admin', 'viewer', 'editor', 'admin'];

/**
 * @param {any} doc parsed OpenAPI document
 * @returns {[string, string][]} [operationId, role] in contract order
 */
export function buildRoles(doc) {
	/** @type {[string, string][]} */
	const out = [];
	for (const [path, item] of Object.entries(doc.paths ?? {})) {
		for (const method of METHODS) {
			const op = item[method];
			if (!op) continue;
			const id = op.operationId;
			const role = op['x-required-role'];
			if (!id) throw new Error(`${method.toUpperCase()} ${path}: missing operationId`);
			if (!ROLES.includes(role)) {
				throw new Error(`${id}: x-required-role ${JSON.stringify(role)} is not one of ${ROLES}`);
			}
			out.push([id, role]);
		}
	}
	return out;
}

/** @param {[string, string][]} roles @param {string} version */
export function render(roles, version) {
	return [
		'// GENERATED by scripts/extract-roles.mjs from contracts/openapi/hub-admin.v1.yaml',
		`// (hub-admin ${version}). Do not edit: run \`npm run gen:api\`.`,
		"import type { operations } from './schema';",
		"import type { Role } from './types';",
		'',
		'/** Minimum role per admin operation (`x-required-role`). */',
		'export const requiredRoles = {',
		...roles.map(([id, role]) => `\t${id}: '${role}',`),
		'} as const satisfies Record<keyof operations, Role>;',
		'',
		'/** An admin operation id, e.g. `purgeDeadLetters`. */',
		'export type OperationId = keyof typeof requiredRoles;',
		''
	].join('\n');
}

function main() {
	const doc = YAML.parse(readFileSync(SPEC, 'utf8'));
	const roles = buildRoles(doc);
	const out = render(roles, doc.info?.version ?? '?');
	if (process.argv.includes('--check')) {
		let current = '';
		try {
			current = readFileSync(OUT, 'utf8');
		} catch {
			/* missing counts as stale */
		}
		if (current !== out) {
			console.error('roles.gen.ts is stale: run `npm run gen:api`');
			process.exit(1);
		}
		return;
	}
	writeFileSync(OUT, out);
	console.log(`extract-roles: ${roles.length} operations -> ${OUT}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
