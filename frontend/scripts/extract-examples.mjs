#!/usr/bin/env node
// Generates src/lib/api/mocks/contract.gen.ts from the `example`s in the admin contract (HUB-252).
//
// For every operation in ../contracts/openapi/hub-admin.v1.yaml it records method, path, the success
// status + example body (+ example response headers such as ETag) and the example error envelope of
// every declared 4xx/5xx. The output is a typed TS module: each example is checked by `svelte-check`
// against the generated `schema.d.ts` types, so a contract change that breaks a mock fails the build.
// Run via `npm run gen:api` (never edit the output by hand). `--check` exits 1 if the file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const SPEC = join(root, '..', 'contracts', 'openapi', 'hub-admin.v1.yaml');
const OUT = join(root, 'src', 'lib', 'api', 'mocks', 'contract.gen.ts');
const METHODS = ['get', 'put', 'post', 'patch', 'delete'];

/**
 * @param {any} doc parsed OpenAPI document
 * @returns {Record<string, any>} mocks by operationId
 */
export function buildMocks(doc) {
	/** @param {any} o */
	const deref = (o) => {
		let cur = o;
		while (cur && typeof cur.$ref === 'string') {
			cur = cur.$ref
				.replace(/^#\//, '')
				.split('/')
				.reduce(
					(/** @type {any} */ a, /** @type {string} */ k) =>
						a?.[k.replace(/~1/g, '/').replace(/~0/g, '~')],
					doc
				);
		}
		return cur;
	};
	/** @param {any} response */
	const jsonExample = (response) => {
		const c = deref(response)?.content?.['application/json'];
		if (!c) return undefined;
		if ('example' in c) return { value: c.example };
		const first = c.examples && Object.values(c.examples)[0];
		return first ? { value: deref(first).value } : undefined;
	};
	/** @type {Record<string, any>} */
	const ops = {};
	for (const [path, item] of Object.entries(doc.paths ?? {})) {
		for (const method of METHODS) {
			const op = item[method];
			if (!op) continue;
			const id = op.operationId;
			if (!id) throw new Error(`${method.toUpperCase()} ${path}: missing operationId`);
			const codes = Object.keys(op.responses ?? {});
			const ok = codes.filter((c) => /^2\d\d$/.test(c)).sort()[0];
			if (!ok) throw new Error(`${id}: no 2xx response`);
			const okResponse = deref(op.responses[ok]);
			const example = jsonExample(okResponse);
			if (!example) throw new Error(`${id}: ${ok} response has no application/json example`);
			/** @type {Record<string, string>} */
			const headers = {};
			for (const [name, h] of Object.entries(okResponse.headers ?? {})) {
				const hv = deref(h);
				if (hv?.example !== undefined) headers[name] = String(hv.example);
			}
			/** @type {Record<string, unknown>} */
			const errors = {};
			for (const c of codes.filter((c) => /^[45]\d\d$/.test(c))) {
				const e = jsonExample(op.responses[c]);
				if (e) errors[c] = e.value;
			}
			// Named examples (HUB-436): every `examples` entry of the JSON request body, the success
			// response and the error responses, by name, for scenario mocks and tests.
			/** @param {any} content */
			const namedOf = (content) =>
				content?.examples
					? Object.fromEntries(
							Object.entries(content.examples).map(([k, v]) => [k, deref(v).value])
						)
					: undefined;
			/** @type {Record<string, any>} */
			const named = {};
			const req = namedOf(deref(op.requestBody)?.content?.['application/json']);
			if (req) named.request = req;
			const res = namedOf(okResponse.content?.['application/json']);
			if (res) named.response = res;
			/** @type {Record<string, any>} */
			const namedErrors = {};
			for (const c of codes.filter((c) => /^[45]\d\d$/.test(c))) {
				const e = namedOf(deref(op.responses[c])?.content?.['application/json']);
				if (e) namedErrors[c] = e;
			}
			if (Object.keys(namedErrors).length) named.errors = namedErrors;
			ops[id] = { method, path, status: Number(ok), headers, example: example.value, errors };
			if (Object.keys(named).length) ops[id].named = named;
		}
	}
	return Object.fromEntries(Object.entries(ops).sort(([a], [b]) => a.localeCompare(b)));
}

/**
 * @param {Record<string, any>} ops
 * @param {string} version
 */
export function render(ops, version) {
	const lines = [
		'// GENERATED by scripts/extract-examples.mjs from contracts/openapi/hub-admin.v1.yaml. DO NOT EDIT.',
		`// Contract version ${version}. Regenerate with \`npm run gen:api\`.`,
		"import type { ContractMocks } from './types';",
		'',
		'export const contractMocks: ContractMocks = {'
	];
	for (const [id, m] of Object.entries(ops)) {
		lines.push(
			`\t${id}: {`,
			`\t\tmethod: '${m.method}',`,
			`\t\tpath: '${m.path}',`,
			`\t\tstatus: ${m.status},`,
			`\t\theaders: ${JSON.stringify(m.headers)},`,
			`\t\texample: ${indent(JSON.stringify(m.example, null, '\t'), 2)},`,
			`\t\terrors: ${indent(JSON.stringify(m.errors, null, '\t'), 2)}${m.named ? ',' : ''}`
		);
		if (m.named) lines.push(`\t\tnamed: ${indent(JSON.stringify(m.named, null, '\t'), 2)}`);
		lines.push('\t},');
	}
	lines.push('};', '');
	return lines.join('\n');
}

/** @param {string} s @param {number} n */
const indent = (s, n) => s.replace(/\n/g, '\n' + '\t'.repeat(n));

function main() {
	const doc = YAML.parse(readFileSync(SPEC, 'utf8'));
	const out = render(buildMocks(doc), doc.info?.version ?? '?');
	if (process.argv.includes('--check')) {
		let current = '';
		try {
			current = readFileSync(OUT, 'utf8');
		} catch {
			/* missing counts as stale */
		}
		if (current !== out) {
			console.error('contract.gen.ts is stale: run `npm run gen:api`');
			process.exit(1);
		}
		return;
	}
	writeFileSync(OUT, out);
	console.log(`extract-examples: ${Object.keys(buildMocks(doc)).length} operations -> ${OUT}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
