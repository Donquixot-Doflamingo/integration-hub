#!/usr/bin/env node
// gen-authz (HUB-478): writes the Rego policies of the Integration Hub admin API from the admin
// contract, one file per operationId, plus the permission catalogue and the generated RBAC matrix
// test. Usage (from the repo root):
//
//   node scripts/gen-authz.mjs            write authz-policies/integration-hub/
//   node scripts/gen-authz.mjs --check    write nothing; exit 1 when a policy is missing, stale, or
//                                         disagrees with the contract (CI runs this)
//   --contract <file>  admin contract (default contracts/openapi/hub-admin.v1.yaml)
//   --out <dir>        policy tree (default authz-policies/integration-hub)
//
// Each operation declares `x-required-role` and `x-required-permission` in the contract. From them
// the generator derives, per operation (AUTH_PLAN §7.3):
//   - the path regex, with the gin-style shadowing exclusions of the ISFC README (a static route such
//     as /snapshots/latest is excluded from /snapshots/{snapshot_version});
//   - the permission the policy asks for ("none": any authenticated caller, getMe);
//   - the scope: "platform" (platform tenant roles and API keys) or "platform+tenant" when the
//     operation's role is tenant_viewer or tenant_admin (a user inside a linked tenant may call it);
//   - machine_allowed: false for the human-only operations (unsealRequest, purgeDeadLetters, D7).
//
// Generated policy files may be edited by hand afterwards (extra conditions, comments). --check
// then compares only the facts that must agree with the contract: operationId, method, path regex,
// permission and scope. tests/rbac_matrix_test.rego and catalogue.json are generated whole and are
// compared byte for byte.
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// The contract toolchain already pins a YAML 1.2 parser (contracts/tools, `make contracts-tools`).
const requireFromTools = createRequire(join(root, 'contracts/tools/package.json'));

const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const opt = (name, def) => (args.includes(name) ? args[args.indexOf(name) + 1] : def);
const checkOnly = flag('--check');
const contractFile = resolve(root, opt('--contract', 'contracts/openapi/hub-admin.v1.yaml'));
const outDir = resolve(root, opt('--out', 'authz-policies/integration-hub'));

const BASE = '/admin/v1'; // the path the Hub sees, after the gateway's prefix rewrite
const PKG = '{__package_name__}'; // replaced at build time with `integrationhub` (ISFC build scripts)
const CONSOLE_CLIENT = 'integration-hub-console';
const HUMAN_ONLY = new Set(['unsealRequest', 'purgeDeadLetters']); // decision D7; backend/.../isfc.go machineRefused
const HEADER = 'GENERATED by scripts/gen-authz.mjs from contracts/openapi/hub-admin.v1.yaml';

// ---- the role catalogue (AUTH_PLAN §7.4) -----------------------------------------------------
// Permissions each role bundles. Roles reproduce exactly today's role matrix; the generator proves it
// (selfCheck) and the generated Rego matrix test proves it again with OPA.
const READS = ['HUB_VENDOR:READ', 'HUB_ACCOUNT:READ', 'HUB_TRANSFORMER:READ', 'HUB_INTEGRATION:READ', 'HUB_TENANT:READ',
  'HUB_REQUEST:READ', 'HUB_DLQ:READ', 'HUB_BREAKER:READ', 'HUB_PLATFORM:READ'];
const WRITES = ['HUB_ACCOUNT:TEST', 'HUB_TRANSFORMER:WRITE', 'HUB_INTEGRATION:WRITE', 'HUB_DLQ:REPLAY'];
const ADMINS = ['HUB_VENDOR:ADMIN', 'HUB_ACCOUNT:ADMIN', 'HUB_TENANT:ADMIN', 'HUB_TENANT:SETUP', 'HUB_REQUEST:UNSEAL',
  'HUB_DLQ:PURGE', 'HUB_BREAKER:ADMIN'];
const TENANT_READS = ['HUB_TENANT:READ', 'HUB_INTEGRATION:READ', 'HUB_REQUEST:READ', 'HUB_DLQ:READ'];
const ROLES = [ // order: strongest first
  { hub: 'admin', isfc: 'HUB_ADMIN', scope: 'platform', permissions: [...READS, ...WRITES, ...ADMINS] },
  { hub: 'editor', isfc: 'HUB_EDITOR', scope: 'platform', permissions: [...READS, ...WRITES] },
  { hub: 'viewer', isfc: 'HUB_VIEWER', scope: 'platform', permissions: [...READS] },
  { hub: 'tenant_admin', isfc: 'HUB_TENANT_ADMIN', scope: 'tenant', permissions: [...TENANT_READS, 'HUB_TENANT:SETUP'] },
  { hub: 'tenant_viewer', isfc: 'HUB_TENANT_VIEWER', scope: 'tenant', permissions: [...TENANT_READS] },
];
// Role hierarchy of the admin API (backend/internal/control/adminapi/auth.go satisfies).
const SATISFIES = {
  admin: ['admin', 'editor', 'viewer', 'tenant_admin', 'tenant_viewer'],
  editor: ['editor', 'viewer', 'tenant_viewer'],
  viewer: ['viewer', 'tenant_viewer'],
  tenant_admin: ['tenant_admin', 'tenant_viewer'],
  tenant_viewer: ['tenant_viewer'],
};
// API keys of the matrix test: key id, client, status, permissions.
const ALL_PERMS = ROLES[0].permissions;

// ---- the contract ----------------------------------------------------------------------------
function loadOperations() {
  const { parse } = requireFromTools('yaml');
  const doc = parse(readFileSync(contractFile, 'utf8'));
  const ops = [];
  for (const [path, item] of Object.entries(doc.paths ?? {})) {
    for (const method of ['get', 'post', 'put', 'patch', 'delete']) {
      const op = item[method];
      if (!op) continue;
      ops.push({
        id: op.operationId, method: method.toUpperCase(), path, tag: (op.tags ?? ['misc'])[0], summary: op.summary ?? '',
        role: op['x-required-role'], permission: op['x-required-permission'],
      });
    }
  }
  return { version: doc.info.version, ops };
}

const errors = [];
const fail = (msg) => errors.push(msg);

function validate(ops) {
  const known = new Set(ROLES.map((r) => r.hub));
  const perms = new Set(ALL_PERMS);
  const ids = new Set();
  for (const op of ops) {
    if (ids.has(op.id)) fail(`duplicate operationId ${op.id}`);
    ids.add(op.id);
    if (!known.has(op.role)) fail(`${op.id}: x-required-role ${JSON.stringify(op.role)} is not one of ${[...known]}`);
    if (op.permission !== 'none' && !perms.has(op.permission)) {
      fail(`${op.id}: x-required-permission ${JSON.stringify(op.permission)} is not in the catalogue (add it to ROLES in gen-authz.mjs and to AUTH_PLAN §7.4)`);
    }
    if (!/^[A-Za-z][A-Za-z0-9]*$/.test(op.id ?? '')) fail(`bad operationId ${op.id}`);
  }
  const used = new Set(ops.map((o) => o.permission));
  for (const p of ALL_PERMS) if (!used.has(p)) fail(`catalogue permission ${p} is used by no operation`);
}

// ---- routing ---------------------------------------------------------------------------------
const segs = (p) => p.split('/').filter(Boolean);
const isParam = (s) => s.startsWith('{');
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const regexOf = (path) => `^${esc(BASE)}/${segs(path).map((s) => (isParam(s) ? '[^/]+' : esc(s))).join('/')}$`;
const sampleOf = (path) => `${BASE}/${segs(path).map((s) => (isParam(s) ? 'x1' : s)).join('/')}`;

// more specific = literal where the other has a parameter, and never the reverse
function dominates(b, a) {
  const sa = segs(a.path), sb = segs(b.path);
  if (a.method !== b.method || sa.length !== sb.length) return false;
  let strictly = false;
  for (let i = 0; i < sa.length; i++) {
    if (isParam(sa[i]) && !isParam(sb[i])) strictly = true;
    else if (!isParam(sa[i]) && isParam(sb[i])) return false;
    else if (!isParam(sa[i]) && sa[i] !== sb[i]) return false;
  }
  return strictly;
}

function exclusions(ops) {
  const out = new Map(ops.map((o) => [o.id, []]));
  for (const a of ops) {
    for (const b of ops) {
      if (a === b || a.method !== b.method || segs(a.path).length !== segs(b.path).length) continue;
      if (dominates(b, a)) out.get(a.id).push(b);
      else if (!dominates(a, b) && segs(a.path).every((s, i) => isParam(s) || isParam(segs(b.path)[i]) || s === segs(b.path)[i]) && a.id < b.id) {
        fail(`routes ${a.method} ${a.path} and ${b.path} overlap and neither is more specific`);
      }
    }
  }
  return out;
}

const scopeOf = (op) => (op.permission === 'none' ? 'any' : ['tenant_viewer', 'tenant_admin'].includes(op.role) ? 'platform+tenant' : 'platform');

// ---- the policy file of one operation --------------------------------------------------------
function policyFile(op, excl, version) {
  const scope = scopeOf(op), machine = !HUMAN_ONLY.has(op.id);
  const perms = op.permission === 'none' ? '[]' : `["${op.permission}"]`;
  const reqs = op.permission === 'none' ? [] : [perms];
  const lines = [];
  lines.push(`package ${PKG}`, '');
  lines.push(`# ${op.summary}`);
  lines.push(`# operationId: ${op.id}`);
  lines.push(`# ${op.method} ${BASE}${op.path}  ·  x-required-role: ${op.role}  ·  x-required-permission: ${op.permission}  ·  scope: ${scope}${machine ? '' : '  ·  human only'}`);
  lines.push(`# ${HEADER} (hub-admin ${version}).`);
  lines.push('# Hand edits may add conditions; `node scripts/gen-authz.mjs --check` fails when the path, permission or scope disagree with the contract.');
  lines.push('');
  lines.push(`match_${op.id} if {`);
  lines.push(`\tregex.match(\`${regexOf(op.path)}\`, input.http.path)`);
  for (const b of excl.get(op.id)) lines.push(`\tnot regex.match(\`${regexOf(b.path)}\`, input.http.path) # ${b.id}: a static route shadows this one`);
  lines.push('}', '');
  const rule = (cond) => {
    lines.push(`permit["${op.method}"][input.http.path] if {`, `\tmatch_${op.id}`, `\t${cond}`, '}', '');
  };
  if (op.permission === 'none') rule('authenticated');
  else if (!machine) rule(`platform_human_can(${reqs[0]})`);
  else {
    rule(`platform_can(${reqs[0]})`);
    if (scope === 'platform+tenant') rule(`tenant_can(${reqs[0]})`);
  }
  lines.push(`details["${op.method}"][input.http.path] := {`);
  lines.push(`\t"operation": "${op.id}",`, `\t"permissions": ${perms},`, `\t"role": "${op.role}",`, `\t"scope": "${scope}",`);
  lines.push(`\t"machine_allowed": ${machine},`, '\t"actual_permissions": object.get(input.sub, "permissions", []),');
  lines.push('} if match_' + op.id, '');
  return lines.join('\n');
}

const fileOf = (op) => `policies/admin/v1/${op.tag}/${op.id}.rego`;

// facts a policy file must keep in agreement with the contract
function factsOf(text) {
  const grab = (re) => (text.match(re) ?? [])[1];
  const permit = [...text.matchAll(/^permit\["([A-Z]+)"\]\[input\.http\.path\] if \{\n\tmatch_(\w+)\n\t(.+)\n\}/gm)];
  return {
    operationId: grab(/^# operationId: (\w+)$/m),
    method: permit.length ? permit[0][1] : undefined,
    regex: grab(/^match_\w+ if \{\n\tregex\.match\(`([^`]*)`, input\.http\.path\)/m),
    permissions: grab(/^\t"permissions": (\[[^\]]*\]),$/m),
    scope: grab(/^\t"scope": "([\w+]+)",$/m),
    machine: grab(/^\t"machine_allowed": (true|false),$/m),
    conds: permit.map((m) => m[3]),
  };
}

function checkPolicy(op, excl, text, file) {
  const f = factsOf(text);
  const want = {
    operationId: op.id, method: op.method, regex: regexOf(op.path), scope: scopeOf(op),
    permissions: op.permission === 'none' ? '[]' : `["${op.permission}"]`, machine: String(!HUMAN_ONLY.has(op.id)),
  };
  for (const k of Object.keys(want)) {
    if (f[k] !== want[k]) fail(`${file}: ${k} is ${JSON.stringify(f[k])}, the contract says ${JSON.stringify(want[k])}`);
  }
  const joined = f.conds.join(' | ');
  const perm = want.permissions;
  const needs = op.permission === 'none' ? ['authenticated'] : HUMAN_ONLY.has(op.id) ? [`platform_human_can(${perm})`]
    : [`platform_can(${perm})`, ...(scopeOf(op) === 'platform+tenant' ? [`tenant_can(${perm})`] : [])];
  for (const n of needs) if (!f.conds.includes(n)) fail(`${file}: no permit rule with ${n} (found: ${joined || 'none'})`);
  for (const c of f.conds) if (!needs.includes(c)) fail(`${file}: unexpected permit condition ${c}; the contract allows ${needs.join(' or ')}`);
}

// ---- catalogue and matrix test ----------------------------------------------------------------
function catalogueJson(version) {
  const doc = {
    $comment: `${HEADER} (hub-admin ${version}). Source: ROLES in scripts/gen-authz.mjs, AUTH_PLAN §7.4. Read by scripts/isfc-seed-hub.py.`,
    console_client: CONSOLE_CLIENT,
    permissions: [...new Set(ALL_PERMS)],
    roles: ROLES.map((r) => ({ name: r.isfc, hub_role: r.hub, scope: r.scope, permissions: r.permissions })),
    human_only_operations: [...HUMAN_ONLY],
  };
  return JSON.stringify(doc, null, 2) + '\n';
}

const q = (s) => JSON.stringify(s);
const regoList = (xs) => `[${xs.map(q).join(', ')}]`;

// The matrix: every operation × role (and × API key) against the real policies. Expectation for a role
// is the role hierarchy, i.e. exactly Principal.Allows in TestRBACMatrix.
function matrixTest(ops, version) {
  const L = [];
  L.push(`package ${PKG}`, '');
  L.push(`# ${HEADER} (hub-admin ${version}). DO NOT EDIT: run \`node scripts/gen-authz.mjs\`.`);
  L.push('#');
  L.push('# Mirrors TestRBACMatrix of backend/internal/control/adminapi: every admin operation × every role,');
  L.push('# with the permissions and the tenant each role has in ISFC, plus API keys (machine principals).');
  L.push('');
  L.push(`rbac_console := ${q(CONSOLE_CLIENT)}`, '');
  L.push('rbac_clients := [{"client_id": rbac_console, "status": "ACTIVE"}]', '');
  L.push('rbac_subs := {');
  for (const r of ROLES) L.push(`\t${q(r.hub)}: {"roles": [${q(r.isfc)}], "permissions": ${regoList(r.permissions)}},`);
  L.push('}', '');
  L.push('# Platform roles are held in the platform tenant, tenant roles in a linked tenant.');
  L.push('rbac_tenants := {');
  for (const r of ROLES) L.push(`\t${q(r.hub)}: ${q(r.scope === 'platform' ? 't-platform' : 't-hl')},`);
  L.push('}', '');
  L.push('rbac_keys := [');
  const keys = [
    ['k-all', 'ci-all', 'ACTIVE', ALL_PERMS],
    ['k-ci', 'ci-integrations', 'ACTIVE', ['HUB_INTEGRATION:WRITE']],
    ['k-read', 'bot-read', 'ACTIVE', READS],
    ['k-inactive', 'ci-all', 'INACTIVE', ALL_PERMS],
    ['k-empty', 'ci-empty', 'ACTIVE', []],
  ];
  for (const [k, c, s, p] of keys) L.push(`\t{"key": ${q(k)}, "allowed_client_id": ${q(c)}, "status": ${q(s)}, "roles": [], "permissions": ${regoList(p)}},`);
  L.push(']', '');
  L.push('rbac_user(role, op) := {');
  L.push('\t"http": {"method": op.method, "path": op.path},');
  L.push('\t"sub": object.union({"id": "u-1", "type": "USER"}, rbac_subs[role]),');
  L.push('\t"client": {"clientId": rbac_console},');
  L.push('\t"tenant": {"id": rbac_tenants[role]},');
  L.push('}', '');
  L.push('rbac_machine(key, client, op) := {');
  L.push('\t"http": {"method": op.method, "path": op.path},');
  L.push('\t"sub": {"id": client, "type": "INTERNAL"},');
  L.push('\t"client": {"clientId": client, "apiKey": key},');
  L.push('}', '');
  L.push(`rbac_allowed(i) if {`);
  L.push(`\tdecision.allow with input as i with data.${PKG}.allowed_client_ids as rbac_clients with data.${PKG}.allowed_api_keys as rbac_keys`);
  L.push('}', '');
  for (const op of ops) {
    const perm = op.permission;
    const o = `{"method": ${q(op.method)}, "path": ${q(sampleOf(op.path))}}`;
    L.push(`# ${op.id}: ${op.method} ${BASE}${op.path} (${op.role}, ${perm})`);
    L.push(`test_rbac_${op.id} if {`);
    L.push(`\top := ${o}`);
    for (const r of ROLES) {
      const roleOk = SATISFIES[r.hub].includes(op.role);
      const permOk = perm === 'none' || r.permissions.includes(perm);
      const scopeOk = r.scope === 'platform' || scopeOf(op) !== 'platform';
      const allowed = roleOk && permOk && scopeOk;
      if (roleOk !== (permOk && scopeOk)) fail(`catalogue drift: ${op.id} needs role ${op.role} (${perm}), but ${r.hub} ${roleOk ? 'satisfies the role without the permission or scope' : 'holds the permission and scope without satisfying the role'}`);
      L.push(`\t${allowed ? '' : 'not '}rbac_allowed(rbac_user(${q(r.hub)}, op))`);
    }
    // An ACTIVE key with permissions, issued to the calling client, holding the operation's permission;
    // never for the human-only operations. A key with no permissions never matches (not even getMe).
    const machineOk = (key) => {
      const ks = keys.find((k) => k[0] === key);
      return !HUMAN_ONLY.has(op.id) && ks[2] === 'ACTIVE' && ks[3].length > 0 && (perm === 'none' || ks[3].includes(perm));
    };
    for (const [k, c] of [['k-all', 'ci-all'], ['k-ci', 'ci-integrations'], ['k-read', 'bot-read'], ['k-inactive', 'ci-all'], ['k-empty', 'ci-empty']]) {
      L.push(`\t${machineOk(k) ? '' : 'not '}rbac_allowed(rbac_machine(${q(k)}, ${q(c)}, op))`);
    }
    L.push(`\tnot rbac_allowed(rbac_machine("k-all", "someone-else", op)) # a key belongs to the client it was issued to`);
    L.push(`\tnot rbac_allowed(rbac_machine("k-unknown", "ci-all", op))`);
    L.push('}', '');
  }
  return L.join('\n');
}

// ---- main --------------------------------------------------------------------------------------
const { version, ops } = loadOperations();
validate(ops);
const excl = exclusions(ops);

const generated = new Map(); // relative path -> content (generated whole)
for (const op of ops) generated.set(fileOf(op), policyFile(op, excl, version));
const wholeFiles = new Map([
  ['tests/rbac_matrix_test.rego', matrixTest(ops, version)],
  ['catalogue.json', catalogueJson(version)],
]);

function listRego(dir) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...listRego(p));
    else if (name.endsWith('.rego')) out.push(relative(outDir, p));
  }
  return out;
}

if (checkOnly) {
  const byFile = new Map(ops.map((o) => [fileOf(o), o]));
  for (const [file, op] of byFile) {
    const p = join(outDir, file);
    if (!existsSync(p)) { fail(`${file}: missing (operation ${op.id}); run node scripts/gen-authz.mjs`); continue; }
    checkPolicy(op, excl, readFileSync(p, 'utf8'), file);
  }
  for (const file of listRego(join(outDir, 'policies'))) {
    if (!byFile.has(file)) fail(`${file}: no operation in the contract has this policy (stale file)`);
  }
  for (const [file, content] of wholeFiles) {
    const p = join(outDir, file);
    if (!existsSync(p)) fail(`${file}: missing; run node scripts/gen-authz.mjs`);
    else if (readFileSync(p, 'utf8') !== content) fail(`${file}: is not what the contract and the catalogue generate; run node scripts/gen-authz.mjs`);
  }
  for (const file of ['entry.rego', 'metadata.yaml', 'tests/entry_test.rego']) {
    if (!existsSync(join(outDir, file))) fail(`${file}: missing`);
  }
} else if (errors.length === 0) {
  for (const [file, content] of [...generated, ...wholeFiles]) {
    const p = join(outDir, file);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
  }
  console.log(`gen-authz: wrote ${generated.size} policies, tests/rbac_matrix_test.rego and catalogue.json to ${relative(root, outDir)} (hub-admin ${version})`);
}

if (errors.length) {
  console.error(`gen-authz: ${errors.length} problem(s)`);
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}
if (checkOnly) console.log(`gen-authz --check: ${ops.length} policies agree with hub-admin ${version}`);
